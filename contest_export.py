def save(plan,directory):
    directory=Path(directory).resolve()
    if not directory.is_dir():raise ValueError('存在する保存先フォルダーを指定してください。')
    for session in plan.sessions:session.snapshot.check(session.path)
    for path,snapshot in plan.guards:snapshot.check(Path(path))
    base=Path(plan.filename)
    for i in range(10000):
        path=directory/(base.stem+('' if i==0 else f'_{i:03d}')+base.suffix)
        if path.exists():continue
        try:replace_bytes(path,plan.data,Snapshot(None,None))
        except ExternalChange:continue
        return path
    raise StorageError('空いている出力ファイル名を確保できません。')

