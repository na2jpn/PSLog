def key(row):return str(row[2]),row[3]
def clean(value,label,required=False,ascii_only=False):
    if not isinstance(value,str):raise ValueError(label+'は文字列で指定してください。')
    value=unicodedata.normalize('NFKC',value).strip()
    if required and not value:raise ValueError(label+'を入力してください。')
    if any(ord(c)<32 or ord(c)==127 for c in value) or '<' in value or '>' in value:raise ValueError(label+'には改行・制御文字・<・>を使用できません。')
    if ascii_only and any(ord(c)>126 for c in value):raise ValueError(label+'は半角英数字・記号で入力してください。')
    return value

def check_jarl_official_required(format,info):
    """Validate fields the official JARL summary-maker marks as required.

    This is intentionally used by the interactive submission UI rather than
    the low-level writer so historical R1.0 files that omitted newer/stricter
    fields can still be reopened and inspected.  Values generated by PSLog
    itself (QSO totals / total score / FD coefficient) are validated by the
    scoring/export pipeline.
    """
    if format not in ('JARL R1.0','JARL R2.1'):
        return
    labels=(
        ('contest','コンテスト名'),('category','部門コード'),
        ('callsign','提出コールサイン'),('address','連絡先住所'),
        ('name','氏名・クラブ局名称'),('power','最大空中線電力'),
        ('email','メールアドレス'),
        ('date','宣誓日'),('signature','署名'),
    )
    for field,label in labels:
        clean(info.get(field,''),label,True)
    if info.get('oath') is not True:
        raise ValueError('宣誓内容を確認してチェックしてください。')
    if format=='JARL R1.0':
        clean(info.get('licenseclass',''),'従事者資格',True)
        powertype=clean(info.get('powertype',''),'出力の記載区分',True)
        if powertype not in ('定格出力','実測出力'):
            raise ValueError('出力の記載区分は「定格出力」または「実測出力」を選択してください。')
    elif info.get('fd') is True:
        clean(info.get('powersupply',''),'使用電源',True)

def token(value,label,required=True):
    v=clean(value,label,required,True)
    if any(c.isspace() for c in v):raise ValueError(label+'の途中に空白は入れられません。')
    return v

def numeric(value):
    s=format(Decimal(str(value)),'f')
    return s.rstrip('0').rstrip('.') if '.' in s else s

def integer(value,label):
    try:v=Decimal(str(value))
    except InvalidOperation:raise ValueError(label+'は整数である必要があります。')
    if not v.is_finite() or v!=v.to_integral_value() or v<0:raise ValueError(label+'は0以上の整数である必要があります。')
    return str(int(v))

def encoded(text,encoding):
    try:return (text+'\r\n').encode(encoding)
    except UnicodeEncodeError as e:raise ValueError('選択した文字コードで出力できない文字があります: '+repr(e.object[e.start:e.end])) from e

def check(selection,rule,draft,context=None):
    if not selection.rows:raise ValueError('対象交信がありません。')
    for session in selection.sessions:session.snapshot.check(session.path)
    own=selection.rows[0][0]
    if rule.get('id')!='iburi_hidaka' and any(r[0]!=own for r in selection.rows):raise ValueError('複数の自局運用を混在して出力できません。')
    for i,r in enumerate(selection.rows):
        if draft.get(key(r),{}).get('status')=='候補・要確認':raise ValueError(f'{i+1}行目の抽出候補を確認してください。')
    work_entries=entries(selection,draft);result=manual_score(work_entries) if rule.get('id')=='manual_other' else score(rule,work_entries,context)
    if result.problems:raise ValueError('採点が未確定です。\n'+'\n'.join(result.problems[:5]))
    return own,result

