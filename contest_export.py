    lines.extend([tag('TOTALSCORE',getattr(result,'ajd_completion','') or numeric(result.total)),tag('ADDRESS',values['address']),tag('NAME',values['name']),tag('POWER',numeric(power))])
    if info.get('fd'):lines.append(tag('FDCOEFF',numeric(result.multi2)))
