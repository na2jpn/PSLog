"""Generate PyInstaller VERSIONINFO from the app's shared version/author."""
from __future__ import annotations

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from product_info import COPYRIGHT, ORGANIZATION
from storage import VERSION


def write_version_info(output, *, updater=False):
    parts = tuple(int(x) for x in VERSION.split('.'))
    if len(parts) > 4 or any(x < 0 or x > 65535 for x in parts):
        raise ValueError('Invalid Windows file version: ' + VERSION)
    version = parts + (0,) * (4 - len(parts))
    name = 'PSLogUpdater.exe' if updater else 'pslog.exe'
    description = 'PSLog Updater' if updater else 'PSLog Amateur Radio Log'
    fields = {
        'CompanyName': ORGANIZATION,
        'FileDescription': description,
        'FileVersion': VERSION,
        'InternalName': Path(name).stem,
        'LegalCopyright': COPYRIGHT,
        'OriginalFilename': name,
        'ProductName': 'PSLog',
        'ProductVersion': VERSION,
    }
    strings = ',\n'.join('        StringStruct(%r, %r)' % item for item in fields.items())
    text = f'''# UTF-8; generated by tools/windows_version_info.py
VSVersionInfo(
  ffi=FixedFileInfo(filevers={version!r}, prodvers={version!r},
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[StringFileInfo([StringTable('041104b0', [
{strings}
    ])]), VarFileInfo([VarStruct('Translation', [1041, 1200])])]
)
'''
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(text, encoding='utf-8')
    return str(output)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output')
    parser.add_argument('--updater', action='store_true')
    args = parser.parse_args()
    write_version_info(args.output, updater=args.updater)
